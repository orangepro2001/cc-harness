// terminalAPI wraps a handler with the terminal policy checks.
func (a *API) terminalAPI(h authed) http.HandlerFunc {
	return a.require(func(w http.ResponseWriter, r *http.Request, user string) {
		if err := a.term.Allowed(user, r); err != nil {
			log.Printf("terminal: denied user=%s ip=%s %s %s: %v", user, clientIP(r), r.Method, r.URL.Path, err)
			writeErr(w, http.StatusForbidden, err.Error())
			return
		}
		h(w, r, user)
	})
}

func (a *API) listTerminals(w http.ResponseWriter, r *http.Request, user string) {
	list, err := a.term.List(user)
	if err != nil {
		writeErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	writeJSON(w, 200, map[string]any{"terminals": list})
}

func (a *API) createTerminal(w http.ResponseWriter, r *http.Request, user string) {
	var req createTermReq
	if r.ContentLength != 0 && !readJSON(w, r, &req) {
		return
	}
	cwd, err := a.mgr.ResolveCwd(user, req.Cwd)
	if err != nil {
		writeErr(w, http.StatusBadRequest, err.Error())
		return
	}
	kind := req.Kind
	title := strings.TrimSpace(req.Title)
	var argv []string
	switch kind {
	case "", "shell":
		kind = "shell"
		argv = []string{a.cfg.TerminalShell, "-l"}
		if title == "" {
			title = filepath.Base(cwd)
		}
	case "claude":
		// Resume a harness session in the real Claude Code CLI. Only the user's own sessions.
		s, err := a.mgr.Get(user, req.Session)
		if err != nil {
			writeErr(w, http.StatusNotFound, "session not found")
			return
		}
		v := s.View()
		if rc, err := a.mgr.ResolveCwd(user, v.Cwd); err == nil {
			cwd = rc
		}
		s.Stop("terminal takeover") // one writer at a time: the harness process must not run beside the CLI
		argv = []string{a.cfg.ClaudeBin, "--resume", v.ID}
		if title == "" {
			title = "claude · " + v.Title
		}
	default:
		writeErr(w, http.StatusBadRequest, "unknown terminal kind")
		return
	}
	title = cleanTitle(title)
	ti, err := a.term.Create(user, cwd, kind, title, argv, req.Cols, req.Rows)
	if err != nil {
		writeErr(w, http.StatusBadRequest, err.Error())
		return
	}
	log.Printf("terminal: create user=%s ip=%s id=%s kind=%s cwd=%s", user, clientIP(r), ti.ID, kind, cwd)
	writeJSON(w, http.StatusCreated, ti)
}

// cleanTitle makes a user-supplied title safe to pass to tmux: a lone ";" (or an argument ending
// in one) is tmux's command separator, and control characters would break the tab-separated listing.
func cleanTitle(t string) string {
	t = strings.Map(func(r rune) rune {
		switch {
		case r == ';':
			return '；'
		case r < 0x20 || r == 0x7f:
			return ' '
		}
		return r
	}, t)
	t = strings.TrimSpace(t)
	if r := []rune(t); len(r) > 100 {
		t = string(r[:100])
	}
	return t
}

func (a *API) deleteTerminal(w http.ResponseWriter, r *http.Request, user string) {
	id := r.PathValue("id")
	if err := a.term.Kill(user, id); err != nil {
		writeErr(w, http.StatusNotFound, err.Error())
		return
	}
	log.Printf("terminal: kill user=%s ip=%s id=%s", user, clientIP(r), id)
	w.WriteHeader(http.StatusNoContent)
}

func qInt(r *http.Request, k string) int {
	n, _ := strconv.Atoi(r.URL.Query().Get(k))
	return n
}

// streamTerminal attaches a tmux client and streams its output as SSE. The first event names the
// attachment, which the input/resize calls refer to. {"d": base64} carries output bytes.
func (a *API) streamTerminal(w http.ResponseWriter, r *http.Request, user string) {
	id := r.PathValue("id")
	att, err := a.term.Attach(user, id, qInt(r, "cols"), qInt(r, "rows"))
	if err != nil {
		code := http.StatusBadRequest
		if err.Error() == "terminal not found" {
			code = http.StatusNotFound
		}
		writeErr(w, code, err.Error())
		return
	}
	defer a.term.release(att)
	log.Printf("terminal: attach user=%s ip=%s id=%s att=%s", user, clientIP(r), id, att.id)
	defer func() {
		log.Printf("terminal: detach user=%s id=%s att=%s after=%s", user, id, att.id, time.Since(att.started).Round(time.Second))
	}()

	rc := http.NewResponseController(w)
	h := w.Header()
	h.Set("Content-Type", "text/event-stream")
	h.Set("Cache-Control", "no-cache, no-transform")
	h.Set("X-Accel-Buffering", "no")
	w.WriteHeader(200)
	emit := func(v any) error {
		b, _ := json.Marshal(v)
		if _, err := fmt.Fprintf(w, "data: %s\n\n", b); err != nil {
			return err
		}
		return rc.Flush()
	}
	if emit(map[string]any{"attach": att.id}) != nil {
		return
	}

	// A client that goes away only shows up on write, so also watch the request context.
	go func() {
		<-r.Context().Done()
		att.close()
	}()
	buf := make([]byte, 16<<10)
	for {
		n, err := att.pty.Read(buf)
		if n > 0 {
			if emit(map[string]string{"d": base64.StdEncoding.EncodeToString(buf[:n])}) != nil {
				return
			}
		}
		if err != nil {
			// the tmux client ended: detached, or the session itself is gone
			emit(map[string]any{"exit": true})
			return
		}
	}
}

func (a *API) termInput(w http.ResponseWriter, r *http.Request, user string) {
	att := a.term.attachment(user, r.PathValue("aid"))
	if att == nil {
		writeErr(w, http.StatusNotFound, "terminal connection not found")
		return
	}
	data, err := io.ReadAll(http.MaxBytesReader(w, r.Body, termMaxInput))
	if err != nil {
		writeErr(w, http.StatusRequestEntityTooLarge, "input too large")
		return
	}
	if _, err := att.pty.Write(data); err != nil {
		writeErr(w, http.StatusGone, "terminal connection closed")
		return
	}
	w.WriteHeader(http.StatusNoContent)
}

func (a *API) termResize(w http.ResponseWriter, r *http.Request, user string) {
	att := a.term.attachment(user, r.PathValue("aid"))
	if att == nil {
		writeErr(w, http.StatusNotFound, "terminal connection not found")
		return
	}
	var req struct{ Cols, Rows int }
	if !readJSON(w, r, &req) {
		return
	}
	cols, rows := clampSize(req.Cols, req.Rows)
	if err := setWinsize(att.pty, cols, rows); err != nil {
		writeErr(w, http.StatusGone, "terminal connection closed")
		return
	}
	w.WriteHeader(http.StatusNoContent)
}
