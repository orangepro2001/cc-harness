// The terminal is a real shell on the server, so it is deliberately opt-in and narrower than the
// rest of the API: enabled per user (HARNESS_TERMINAL), reachable only from allowed networks
// (loopback + Tailscale by default) and audited in the service log.
//
// Persistence comes from tmux: every terminal is a detached tmux session, and each screen
// connection is a short-lived `tmux attach` client on a PTY. Dropping the connection (phone
// locked, link lost) only kills that client; reconnecting repaints the session from tmux.

const (
	termMinCols, termMaxCols = 10, 500
	termMinRows, termMaxRows = 3, 200
	termMaxInput             = 64 << 10
	termMaxAttach            = 6 // simultaneous screen connections per user
)

var termIDRe = regexp.MustCompile(`^cch[0-9a-f]{8}$`)

const tmuxConf = `# generated by cc-harness; rewritten on start
set -g status off
set -g mouse on
set -g history-limit 50000
set -g escape-time 10
set -g window-size latest
set -g aggressive-resize on
set -g default-terminal "tmux-256color"
set -ga terminal-features ",*:RGB"
set -g set-clipboard on
set -g allow-passthrough off
set -g destroy-unattached off
set -g exit-empty off
`

type Terminals struct {
	cfg  Config
	conf string

	mu     sync.Mutex
	attach map[string]*attachment
}

type attachment struct {
	id, user, term string
	pty            *os.File
	cmd            *exec.Cmd
	started        time.Time
	once           sync.Once
}

func (a *attachment) close() {
	a.once.Do(func() {
		a.pty.Close()
		if a.cmd.Process != nil {
			a.cmd.Process.Kill() // only the tmux client; the session itself keeps running
		}
		go a.cmd.Wait()
	})
}

func NewTerminals(cfg Config) *Terminals {
	return &Terminals{cfg: cfg, conf: filepath.Join(cfg.DataDir, "tmux.conf"), attach: map[string]*attachment{}}
}

// enabledFor reports whether the user may have terminals at all.
func (t *Terminals) enabledFor(user string) bool {
	for _, u := range t.cfg.TerminalUsers {
		if u == "*" || u == user {
			return true
		}
	}
	return false
}

// netAllowed checks the TCP peer address; proxy headers are never trusted for this.
func (t *Terminals) netAllowed(r *http.Request) bool {
	if t.cfg.TerminalNets == nil {
		return true
	}
	ip := net.ParseIP(clientIP(r))
	if ip == nil {
		return false
	}
	for _, n := range t.cfg.TerminalNets {
		if n.Contains(ip) {
			return true
		}
	}
	return false
}

// Allowed returns nil when this request may use the terminal API.
func (t *Terminals) Allowed(user string, r *http.Request) error {
	if !t.enabledFor(user) {
		return errors.New("terminal is not enabled for this user")
	}
	if !t.netAllowed(r) {
		return errors.New("terminal is only available from the local machine or the tailnet")
	}
	return nil
}

func (t *Terminals) tmuxBin() (string, error) {
	if t.cfg.TmuxBin != "" {
		return t.cfg.TmuxBin, nil
	}
	return exec.LookPath("tmux")
}

func (t *Terminals) socket() string {
	if t.cfg.TmuxSocket != "" {
		return t.cfg.TmuxSocket
	}
	return "cch"
}

// env is the service environment minus our own secrets: the shell must not inherit HARNESS_PASSWORD.
func (t *Terminals) env() []string {
	var out []string
	hasLang := false
	for _, kv := range os.Environ() {
		if strings.HasPrefix(kv, "HARNESS_") || strings.HasPrefix(kv, "TERM=") || strings.HasPrefix(kv, "TMUX=") {
			continue
		}
		if strings.HasPrefix(kv, "LANG=") || strings.HasPrefix(kv, "LC_ALL=") {
			hasLang = true
		}
		out = append(out, kv)
	}
	if !hasLang {
		out = append(out, "LANG=C.UTF-8")
	}
	return append(out, "TERM=xterm-256color", "COLORTERM=truecolor")
}

func (t *Terminals) tmux(args ...string) (string, error) {
	bin, err := t.tmuxBin()
	if err != nil {
		return "", errors.New("tmux is not installed on the server")
	}
	if err := os.WriteFile(t.conf, []byte(tmuxConf), 0o600); err != nil {
		return "", err
	}
	full := append([]string{"-L", t.socket(), "-f", t.conf}, args...)
	cmd := exec.Command(bin, full...)
	cmd.Env = t.env()
	var out, errb bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errb
	if err := cmd.Run(); err != nil {
		msg := strings.TrimSpace(errb.String())
		if msg == "" {
			msg = err.Error()
		}
		return out.String(), errors.New(msg)
	}
	return out.String(), nil
}

type TermInfo struct {
	ID        string `json:"id"`
	Title     string `json:"title"`
	Kind      string `json:"kind"` // shell | claude
	Cwd       string `json:"cwd"`
	CreatedAt string `json:"createdAt"`
	Attached  int    `json:"attached"`
}

func noServer(err error) bool {
	if err == nil {
		return false
	}
	m := err.Error()
	return strings.Contains(m, "no server running") || strings.Contains(m, "No such file or directory") ||
		strings.Contains(m, "error connecting") || strings.Contains(m, "no sessions")
}

// List returns the user's terminals (tmux sessions carrying their owner tag).
func (t *Terminals) List(user string) ([]TermInfo, error) {
	out, err := t.tmux("list-sessions", "-F", "#{session_name}\t#{@cch_owner}\t#{@cch_title}\t#{@cch_kind}\t#{session_created}\t#{session_attached}\t#{pane_current_path}")
	if err != nil {
		if noServer(err) {
			return []TermInfo{}, nil
		}
		return nil, err
	}
	res := []TermInfo{}
	for _, line := range strings.Split(strings.TrimSpace(out), "\n") {
		f := strings.Split(line, "\t")
		if len(f) < 7 || f[1] != user || !termIDRe.MatchString(f[0]) {
			continue
		}
		created := ""
		if sec, err := strconv.ParseInt(f[4], 10, 64); err == nil {
			created = time.Unix(sec, 0).UTC().Format(time.RFC3339)
		}
		att, _ := strconv.Atoi(f[5])
		res = append(res, TermInfo{ID: f[0], Title: f[2], Kind: f[3], Cwd: f[6], CreatedAt: created, Attached: att})
	}
	return res, nil
}

func (t *Terminals) owns(user, id string) (TermInfo, bool) {
	if !termIDRe.MatchString(id) {
		return TermInfo{}, false
	}
	list, err := t.List(user)
	if err != nil {
		return TermInfo{}, false
	}
	for _, ti := range list {
		if ti.ID == id {
			return ti, true
		}
	}
	return TermInfo{}, false
}

func clampSize(cols, rows int) (int, int) {
	if cols < termMinCols {
		cols = 80
	}
	if rows < termMinRows {
		rows = 24
	}
	if cols > termMaxCols {
		cols = termMaxCols
	}
	if rows > termMaxRows {
		rows = termMaxRows
	}
	return cols, rows
}

type createTermReq struct {
	Cwd     string `json:"cwd"`
	Kind    string `json:"kind"`    // shell (default) | claude
	Session string `json:"session"` // claude: resume this harness session
	Title   string `json:"title"`
	Cols    int    `json:"cols"`
	Rows    int    `json:"rows"`
}

func (t *Terminals) Create(user, cwd, kind, title string, argv []string, cols, rows int) (TermInfo, error) {
	list, err := t.List(user)
	if err != nil {
		return TermInfo{}, err
	}
	if len(list) >= t.cfg.TerminalMax {
		return TermInfo{}, fmt.Errorf("at most %d terminals per user: close one first", t.cfg.TerminalMax)
	}
	b := make([]byte, 4)
	if _, err := rand.Read(b); err != nil {
		return TermInfo{}, err
	}
	id := "cch" + hex.EncodeToString(b)
	cols, rows = clampSize(cols, rows)
	args := []string{
		"new-session", "-d", "-s", id, "-x", strconv.Itoa(cols), "-y", strconv.Itoa(rows), "-c", cwd, "--",
	}
	args = append(args, argv...)
	args = append(args, ";", "set-option", "-t", id, "@cch_owner", user,
		";", "set-option", "-t", id, "@cch_title", title,
		";", "set-option", "-t", id, "@cch_kind", kind)
	if _, err := t.tmux(args...); err != nil {
		return TermInfo{}, err
	}
	return TermInfo{ID: id, Title: title, Kind: kind, Cwd: cwd, CreatedAt: time.Now().UTC().Format(time.RFC3339)}, nil
}

func (t *Terminals) Kill(user, id string) error {
	if _, ok := t.owns(user, id); !ok {
		return errors.New("terminal not found")
	}
	t.mu.Lock()
	for _, a := range t.attach {
		if a.term == id {
			a.close()
		}
	}
	t.mu.Unlock()
	_, err := t.tmux("kill-session", "-t", id)
	return err
}

// Attach starts a tmux client for the terminal on a new PTY of the given size.
func (t *Terminals) Attach(user, id string, cols, rows int) (*attachment, error) {
	if _, ok := t.owns(user, id); !ok {
		return nil, errors.New("terminal not found")
	}
	t.mu.Lock()
	n := 0
	for _, a := range t.attach {
		if a.user == user {
			n++
		}
	}
	t.mu.Unlock()
	if n >= termMaxAttach {
		return nil, errors.New("too many open terminal screens")
	}
	bin, err := t.tmuxBin()
	if err != nil {
		return nil, errors.New("tmux is not installed on the server")
	}
	cols, rows = clampSize(cols, rows)
	cmd := exec.Command(bin, "-L", t.socket(), "-f", t.conf, "attach-session", "-t", id)
	cmd.Env = t.env()
	master, err := startPTY(cmd, cols, rows)
	if err != nil {
		return nil, err
	}
	raw := make([]byte, 8)
	rand.Read(raw)
	a := &attachment{id: hex.EncodeToString(raw), user: user, term: id, pty: master, cmd: cmd, started: time.Now()}
	t.mu.Lock()
	t.attach[a.id] = a
	t.mu.Unlock()
	return a, nil
}

func (t *Terminals) release(a *attachment) {
	a.close()
	t.mu.Lock()
	delete(t.attach, a.id)
	t.mu.Unlock()
}

func (t *Terminals) attachment(user, id string) *attachment {
	t.mu.Lock()
	defer t.mu.Unlock()
	if a := t.attach[id]; a != nil && a.user == user {
		return a
	}
	return nil
}

// KillAttachments drops every screen connection (service shutdown); the tmux sessions survive.
func (t *Terminals) KillAttachments() {
	t.mu.Lock()
	defer t.mu.Unlock()
	for _, a := range t.attach {
		a.close()
	}
}

